"""Generate browser metadata from the vendored, pinned image profile.

Run after reviewing an upstream update and replacing the vendored sources.
Use --check in tests/CI to detect metadata or license drift.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from sq64_emulator.conformance import SPEC_SOURCE
from sq64_emulator._vendor.sq64_spec.report import catalog, model_contract_digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    document = catalog()
    metadata = dict(specVersion=document['version'], specSource=SPEC_SOURCE,
                    modelContractSha256=model_contract_digest(),
                    requirements=[{'id': r['id'], 'verification': r['verification']}
                                  for r in document['requirements'] if 'image' in r['profiles']])
    target = ROOT / 'web/emulator/conformance'
    files = {
        target / 'spec.js': '// Generated by tools/sync_conformance.py; do not edit.\nexport default ' + json.dumps(metadata, indent=2) + ';\n',
        target / 'LICENSE': (ROOT / 'sq64_emulator/_vendor/sq64_spec/LICENSE').read_text(encoding="utf-8"),
    }
    for path, content in files.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f'Conformance metadata drift: {path}')
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == '__main__':
    main()
